import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import express from 'express';
import { registerComparisonRoutes } from './comparisons.js';

test('comparisons enforce ownership and fixed seeds, persist votes and redact removed images', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-compare-'));
  let items = ['a', 'b', 'c'].map(jobId => ({ id: jobId, jobId, ownerId: jobId === 'c' ? 'other' : 'owner', type: 'image', status: 'done', settings: { seed: '42' }, prompt: 'private' }));
  const app = express(); app.use(express.json()); app.use((req, res, next) => { req.studioAccount = { userId: req.headers['x-test-owner'] || 'owner', authenticated: true, role: 'administrator' }; next(); });
  registerComparisonRoutes(app, { dataDir: dir, gallery: () => items });
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(() => { server.closeAllConnections(); server.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const request = (route, body, method = 'POST', owner = 'owner') => fetch(`http://127.0.0.1:${server.address().port}/api/comparisons${route}`, { method, headers: { 'content-type': 'application/json', 'x-test-owner': owner }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await request('', { jobIds: ['a', 'c'] })).status, 404);
  items[1].settings.seed = '43'; assert.equal((await request('', { jobIds: ['a', 'b'] })).status, 400);
  items[1].settings.seed = '42';
  const created = await (await request('', { jobIds: ['a', 'b'] })).json(); assert.equal(created.seed, '42');
  assert.deepEqual((await (await request('', null, 'GET', 'other')).json()).comparisons, []);
  assert.equal((await request(`/${created.id}/vote`, { jobId: 'a' }, 'PUT', 'other')).status, 404);
  assert.equal((await request(`/${created.id}/vote`, { jobId: 'c' }, 'PUT')).status, 400);
  assert.equal((await (await request(`/${created.id}/vote`, { jobId: 'b' }, 'PUT')).json()).vote, 'b');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'comparisons.json')))[0].vote, 'b');
  items = items.filter(item => item.jobId !== 'b');
  const history = (await (await request('', null, 'GET')).json()).comparisons;
  assert.equal(history[0].variants[1].item, null);
  assert.equal(history[0].vote, null);
  assert.equal((await request(`/${created.id}/vote`, { jobId: null }, 'PUT')).status, 200);
  assert.equal((await request(`/${created.id}/vote`, { jobId: 'b' }, 'PUT')).status, 400);
  items = ['a', 'b'].map(jobId => ({ id: jobId, jobId, ownerId: 'owner', type: 'image', status: 'done', settings: { seed: 0 } }));
  const zero = await request('', { jobIds: ['a', 'b'] });
  assert.equal(zero.status, 201);
  assert.equal((await zero.json()).seed, '0');
});
